    b = parse(t['jun'], MONTHS_JUN, cols)
    overlap = [k for k in a if k in b]
    diff = [k for k in overlap if a[k] != b[k]]
    print(f'{ap}: {len(overlap)} overlapping cells compared, {len(diff)} differ {diff}')
    for c in cols:
        year = [(a[(m, c)], DAYS[m]) for m in YEAR if a[(m, c)] is not None]
