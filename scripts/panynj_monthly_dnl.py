def parse(text, months, cols):
    rows = [r.split() for r in text.strip().splitlines()]
    assert len(rows) == len(months), (len(rows), len(months))
    assert all(len(r) == len(cols) for r in rows), [len(r) for r in rows]
    return {(m, c): (None if v == 'NA' else float(v)) for m, r in zip(months, rows, strict=True) for c, v in zip(cols, r, strict=True)}


def emean(vals):
    return round(10 * math.log10(sum(d * 10 ** (v / 10) for v, d in vals) / sum(d for _, d in vals)), 1)


