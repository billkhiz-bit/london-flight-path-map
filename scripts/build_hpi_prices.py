"""Borough `avgPrice` and `trend` from HM Land Registry UK HPI, keyed on ONS codes.

Why this exists
---------------
Both fields were entered by hand for every city, with no script and no cached
dataset, so nothing in the repo could re-derive them and nothing could notice
when one of them drifted. That is not hypothetical: as of 2026-08-10 London's
`avgPrice` matches HPI 2026-05 for all 33 boroughs while its `trend` matches
**no HPI month at all**, and Greater Manchester's matches 2026-05 for all ten.
Two cities, one provenance sentence in CITY_PROVENANCE, two different sources.

WHY ONS CODES AND NOT NAMES
---------------------------
Name matching has failed this project five separate times, and every failure
looked like missing data rather than a spelling difference:

  * `Brentwood` (Essex) matched the London borough key `Brent` and was drawn as
    a London borough, feeding the map projection an outlier 30 km out.
  * `ST. HELENS` in Price Paid did not match a district list, and was recorded
    as Merseyside having only 4 of 5 districts.
  * `VALE OF GLAMORGAN` did not match either - Price Paid calls it
    `THE VALE OF GLAMORGAN`, with the article.
  * `NOTTINGHAM` did not match; Price Paid calls it `CITY OF NOTTINGHAM`.
  * `Westminster` finds no HPI row; HPI calls it `City of Westminster`.

The same place is spelled differently in two datasets from the same department:
Price Paid says `ST. HELENS`, HPI says `St Helens`. A code cannot be spelled
differently. CITY_LADS below was GENERATED by resolving names against the HPI
file once and pinning the result, not typed from memory - which caught that
Barnsley and Sheffield are E08000038 and E08000039, not the E08000016 and
E08000019 they are widely reported as.

Usage
-----
    python scripts/build_hpi_prices.py --check --city london
    python scripts/build_hpi_prices.py --check --all
    python scripts/build_hpi_prices.py --emit --city westmidlands

`--check` compares what the score Lambda holds against HPI and exits non-zero on
drift, so it can sit in preflight. `--emit` prints a paste-ready borough block
for a city that does not exist yet. Re-run `--check` after every HPI release
(monthly); drift is the signal to roll the vintage, not a bug.
"""

