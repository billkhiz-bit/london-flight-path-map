"""SFO's 29 noise monitors for the US yardstick, from DataSF (2026-10-16).

The SFO block of data/us-noise-monitors.json, made reproducible: it was first computed
by scratch code. Source: DataSF "Aircraft Noise Climates" (qxw2-ncq3), PDDL 1.0, daily
aircraft CNEL per monitor, July 2025 - June 2026 (the SJC report's period).

Both readings are kept per monitor. cnel_db is the conventional threshold method;
aneem_cnel_db is ANEEM, which also captures quieter aircraft events. At sites over
55 dB the two agree within a few tenths; below, ANEEM reads up to 9.5 dB higher
(Millbrae, Burlingame), because the conventional method never counts the quieter
events there. The yardstick is ANEEM ('yardstick': 'aneem', Bill 2026-10-16): the more
complete measurement, and the louder, so the safe side of a rule that the estimate must
not read quieter than measured.

A year is the energy mean of the days with at least 90% monitor uptime:
10 log10(mean 10^(L/10)). The method reproduces SJC's published annual CNEL from its
monthly values to 0.05 dB (4 of 4 monitors tried).

  python scripts/build_sfo_noise_monitors.py --fetch   download the year's daily rows (gitignored)
  python scripts/build_sfo_noise_monitors.py --write   rewrite the SFO block from them
  python scripts/build_sfo_noise_monitors.py --check   the block equals what --write would write
"""

import argparse
import csv
import json
import math
import sys
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / 'data' / 'us-noise-monitors.json'
RAW = REPO / 'data' / 'us-monitors' / 'sfo-datasf' / 'daily-2025-07_2026-06.csv'
PERIOD = ('2025-07-01', '2026-06-30')
UPTIME = 0.9 * 86400
URL = 'https://data.sf.gov/resource/qxw2-ncq3.csv'


def emean(values):
    return round(10 * math.log10(sum(10 ** (v / 10) for v in values) / len(values)), 1)


def block():
    rows = defaultdict(list)
    with open(RAW, encoding='utf-8') as fh:
        for r in csv.DictReader(fh):
            if r['uptime'] and float(r['uptime']) >= UPTIME:
                rows[r['location_id']].append(r)
    monitors = []
    for sid in sorted(rows, key=int):
        rs = rows[sid]
        aneem = [float(r['aircraft_cnel_aneem']) for r in rs if r['aircraft_cnel_aneem']]
        monitors.append({
            'id': sid, 'location': rs[0]['location'], 'lat': float(rs[0]['latitude']), 'lon': float(rs[0]['longitude']),
            'cnel_db': emean([float(r['aircraft_cnel']) for r in rs]),
            # ANEEM is missing on a few days at some sites: use the days that carry it, and only
            # when they are at least 90% of the monitor's good days.
            'aneem_cnel_db': emean(aneem) if len(aneem) >= 0.9 * len(rs) else None,
            'aneem_days': len(aneem),
            'sfo_only_cnel_db': emean([float(r['sfo_cnel']) for r in rs]),
            'days': len(rs),
        })
    return {
        'publisher': 'San Francisco International Airport (SFO), Noise Abatement Office, via DataSF',
        'report': "DataSF 'Aircraft Noise Climates' (dataset qxw2-ncq3), daily Aircraft CNEL per monitor",
        'url': URL,
        'licence': 'Open Data Commons Public Domain Dedication and License (PDDL) 1.0, read from the dataset metadata 2026-10-16',
        'period': list(PERIOD),
        'yardstick': 'aneem',
        'system': ("SFO's 29 community noise monitors. cnel_db: all aircraft events, conventional threshold method; "
                   'aneem_cnel_db: the same with ANEEM, which also captures quieter aircraft events (the YARDSTICK); '
                   "sfo_only_cnel_db: SFO's own aircraft, conventional"),
        'coordinates_from': 'the dataset latitude/longitude columns (rounded by the publisher to 3 decimal places, about 100 m)',
        'cnel_from': ('energy mean of the daily values over days with at least 90% monitor uptime, generated by '
                      'scripts/build_sfo_noise_monitors.py; the method reproduces SJC\'s published annual CNEL from its '
                      'monthly values to 0.05 dB at 4 of 4 monitors tried (101, 104, 108, 111)'),
        'monitors': monitors,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--fetch', action='store_true')
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if a.fetch:
        RAW.parent.mkdir(parents=True, exist_ok=True)
        q = urllib.parse.urlencode({'$where': f"date between '{PERIOD[0]}T00:00:00' and '{PERIOD[1]}T23:59:59'",
                                    '$limit': '50000', '$order': 'date,location_id'})
        req = urllib.request.Request(f'{URL}?{q}', headers={'User-Agent': 'SkyScore/1.0 (support@skyscore.co.uk)'})
        with urllib.request.urlopen(req, timeout=120) as r:
            RAW.write_bytes(r.read())
        print(f'fetched {RAW.relative_to(REPO)} ({RAW.stat().st_size:,} bytes)')
        return 0
    with open(DATA, encoding='utf-8') as fh:
        doc = json.load(fh)
    if not RAW.exists():
        print(f'INCONCLUSIVE: {RAW.relative_to(REPO)} is not on disk (run --fetch)')
        return 0
    fresh = block()
    if a.check:
        same = doc['airports'].get('SFO') == fresh
        print('SFO block ' + ('equals' if same else 'DIFFERS FROM') + f' the daily rows ({len(fresh["monitors"])} monitors)')
        return 0 if same else 1
    doc['airports']['SFO'] = fresh
    with open(DATA, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(doc, fh, indent=2, ensure_ascii=False)
        fh.write('\n')
    print(f'wrote the SFO block: {len(fresh["monitors"])} monitors, yardstick {fresh["yardstick"]}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
