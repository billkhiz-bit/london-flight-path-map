"""The Bay Area's 50 city records for the score Lambda, from the release 2 readers' files (2026-10-22).

Build-order step 4's first half (ROADMAP "Release 2 plan"): one record per city, written between the
BAYAREA-BOROUGHS markers in backend/lambdas/score/app.py, joined BY GEOID from the committed files each reader
writes, never typed:

  impact               data/us-bayarea-quiet.json       the fitted estimate over residents, err-loud band
  avgPrice             data/us-bayarea-prices.json      ACS median value; 2,000,001 is the "$2M+" top code,
  priceTopCoded                                         kept in the formula and flagged (Bill, 2026-10-17)
  trend, county        data/us-bayarea-trend.json       FHFA, county-wide (decision 3)
  crimePer1000Us       data/us-bayarea-crime.json       DOJ over Census; None for the sheriff-contract cities
  crimeFewResidents
  transport            data/us-bayarea-transport.json   rail access, banded (Bill, 2026-10-22); None for Emeryville
  roadNoiseUsSharePct  data/us-bayarea-road.json        BTS, residents at 45 dB LAeq or louder
  floodSfhaPct         data/us-bayarea-flood.json       FEMA 1% zone; None where FEMA has not determined the risk

and `withheld`, present only on a city missing an input: the reader's own reason, per field, so a response can
say why rather than leave a gap. The US measures carry their OWN field names, so the UK ramps (crime_to_score,
road_to_score, flood_to_score) cannot be applied to them by mistake: they are scored on the US scale,
us_anchored_to_score, against US_CALIFORNIA_ANCHORS, which this writes beside the records from the same files
(California's crime rate, road share and flood share, each read from its reader's file).

The SAME records are written a second time, for the site (the release of the site's scores, 2026-11-07): between
the BAYAREA-RECORDS markers in index.html, with the anchors, the price top code and the few-residents note READ from
app.py, so the full map scores each city from what the API scores it from. One derivation, two holders; --check
holds both, and tests/test_borough_data_parity.py reads both back independently.

  python scripts/build_bayarea_records.py --write   rewrite both blocks
  python scripts/build_bayarea_records.py --check   both blocks == what the files give (offline, every file committed)
"""

import argparse
import ast
import calendar
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / 'data'
LAMBDA = REPO / 'backend' / 'lambdas' / 'score' / 'app.py'
START = '# BAYAREA-BOROUGHS:START (generated by scripts/build_bayarea_records.py --write; do not hand-edit)'
END = '# BAYAREA-BOROUGHS:END'
SITE = REPO / 'index.html'
SITE_START = '      // BAYAREA-RECORDS:START (generated by scripts/build_bayarea_records.py --write; do not hand-edit)'
SITE_END = '      // BAYAREA-RECORDS:END'
# Read from app.py, never retyped: the site must show the API's top code and the API's own words.
LAMBDA_CONSTANTS = ('US_PRICE_TOP_CODE', '_CRIME_FEW_RESIDENTS_NOTE')
PLACE_KINDS = ('city', 'town')


def _read(name):
    return json.loads((DATA / name).read_text(encoding='utf-8'))


def _by_geoid(rows, source, want):
    out = {r['geoid']: r for r in rows}
    if len(out) != len(rows) or set(out) != want:
        raise SystemExit(f'{source}: its cities are not exactly the 50 of us-bayarea-places.json, once each')
    return out


def records():
    """(anchors, [(name, record)]) from the readers' files, in name order."""
    places = [p for p in _read('us-bayarea-places.json')['places'] if p['kind'] in PLACE_KINDS]
    want = {p['geoid'] for p in places}
    quiet = _by_geoid(_read('us-bayarea-quiet.json')['cities'], 'us-bayarea-quiet.json', want)
    prices = _by_geoid(_read('us-bayarea-prices.json')['cities'], 'us-bayarea-prices.json', want)
    crime_doc = _read('us-bayarea-crime.json')
    crime = _by_geoid(crime_doc['cities'], 'us-bayarea-crime.json', want)
    transport = _by_geoid(_read('us-bayarea-transport.json')['cities'], 'us-bayarea-transport.json', want)
    road_doc = _read('us-bayarea-road.json')
    road = _by_geoid(road_doc['cities'], 'us-bayarea-road.json', want)
    flood = _by_geoid(_read('us-bayarea-flood.json')['cities'], 'us-bayarea-flood.json', want)
    trend = {c['county']: c['annual_change_pct'] for c in _read('us-bayarea-trend.json')['counties']}
    anchors = {
        'crimePer1000Us': crime_doc['california']['per_1000'],
        'roadNoiseUsSharePct': road_doc['california']['share_at_or_above_45_db_pct'],
        'floodSfhaPct': _read('us-california-flood.json')['sfha_pct'],
    }
    for k, v in anchors.items():
        if not isinstance(v, (int, float)) or v <= 0:
            raise SystemExit(f'the {k} anchor is {v!r}: a US scale needs a positive one')
    out = []
    for p in sorted(places, key=lambda p: p['name']):
        g = p['geoid']
        if p['county'] not in trend:
            raise SystemExit(f"{p['name']}: no FHFA trend for {p['county']} County")
        price = prices[g]
        rec = {
            'impact': quiet[g]['band'],
            'avgPrice': price['median_value_usd'],
            'priceTopCoded': price['top_coded'],
            'trend': trend[p['county']],
            'county': p['county'],
            'crimePer1000Us': crime[g]['per_1000'],
            'crimeFewResidents': crime[g]['few_residents'],
            'transport': transport[g]['band'],
            'roadNoiseUsSharePct': road[g]['share_at_or_above_45_db_pct'],
            'floodSfhaPct': flood[g]['sfha_pct'],
        }
        withheld = {}
        if rec['crimePer1000Us'] is None:
            withheld['crimePer1000Us'] = crime[g]['no_rate']
        if rec['transport'] is None:
            withheld['transport'] = transport[g]['withheld']
        if rec['floodSfhaPct'] is None:
            withheld['floodSfhaPct'] = flood[g]['withheld']
        if rec['roadNoiseUsSharePct'] is None or rec['impact'] is None or rec['avgPrice'] is None:
            raise SystemExit(f"{p['name']}: road, quiet or price is missing, and no reader withholds those")
        if any(not reason for reason in withheld.values()):
            raise SystemExit(f"{p['name']}: an input is missing without its reader's reason")
        if withheld:
            rec['withheld'] = withheld
        out.append((p['name'], rec))
    return anchors, out


# WHAT EACH FIGURE IS, AND FROM WHEN (Bill, 2026-11-07: "keep the raw input figures, each with its source and
# year"). The publisher is named here; the YEAR is read from the reader's own file, never typed, so a roll of any
# input moves its label on the map, the front page and the area pages at once.
def input_sources():
    """{record field: 'publisher, year'} for every input a Bay Area figure is printed from."""
    prices = _read('us-bayarea-prices.json')
    trend_years = {c['year'] for c in _read('us-bayarea-trend.json')['counties']}
    if len(trend_years) != 1:
        raise SystemExit(f'us-bayarea-trend.json: the counties hold different years {sorted(trend_years)}')
    compiled = _read('us-bayarea-transit.json')['compiled']
    edition = re.search(r'NTAD_Noise_(\d{4})_', _read('us-bayarea-road.json')['service'])
    if not edition:
        raise SystemExit("us-bayarea-road.json: the BTS service no longer names its edition's year")
    fetched = _read('us-bayarea-flood.json')['fema_fetched_utc']
    read = f'{calendar.month_name[int(fetched[5:7])]} {fetched[:4]}'
    return {
        'avgPrice': f"US Census Bureau American Community Survey 5-year estimates, {prices['vintage']}",
        'trend': f'FHFA county house price index, {trend_years.pop()}',
        'crimePer1000Us': f"California DOJ OpenJustice, {_read('us-bayarea-crime.json')['year']}",
        'transport': f'BTS National Transit Map, compiled {max(compiled)[:4]}',
        'roadNoiseUsSharePct': f'BTS National Transportation Noise Map, {edition.group(1)}',
        'floodSfhaPct': f'FEMA National Flood Hazard Layer, as read {read}',
    }


def us_scales(n_cities):
    """Said wherever a Bay Area score shows (Bill's rule): its US scales are not the UK's."""
    return (f"On US scales: crime, road noise and flood risk are scored against California's own figures, and prices "
            f"among the Bay Area's {n_cities} cities alone. Not comparable with a UK score, nor with New York's.")


INPUT_LABELS = {'crimePer1000Us': 'Crime', 'transport': 'Rail access', 'floodSfhaPct': 'Flood risk'}


def input_facts(name, rec, anchors, sources, top_code, crime_note=None):
    """[(label, figure, source)] for one city's inputs, in plain words: the front page's card and the area pages
    say each figure, with its source and year, from here (the full map says the same from the same block)."""
    held = rec.get('withheld') or {}

    def scale(field, unit=''):
        return f"10 at none, 5 at California's {anchors[field]}{unit}, 0 at double or more"

    def withheld(field):
        return f'Withheld, not estimated: {held[field]}'

    price = (f'${top_code / 1_000_000:g}M or more (the Census\'s top code)' if rec['priceTopCoded']
             else f"${rec['avgPrice']:,}")
    trend = rec['trend']
    out = [
        ('Median home value', price, sources['avgPrice']),
        ('County price trend', f"{rec['county']} County, {trend:+g}% in a year (a fact, not scored: county-wide)", sources['trend']),
    ]
    if rec['crimePer1000Us'] is not None:
        note = f' {crime_note}' if rec.get('crimeFewResidents') and crime_note else ''
        out.append(('Crime', f"{rec['crimePer1000Us']:g} per 1,000 residents a year, scored {scale('crimePer1000Us')}.{note}",
                    sources['crimePer1000Us']))
    else:
        out.append(('Crime', withheld('crimePer1000Us'), sources['crimePer1000Us']))
    if rec['transport'] is not None:
        out.append(('Rail access', f"{rec['transport'].title()}: the share of residents within 800 m of a rail, metro "
                    'or light-rail station, banded as the UK is (buses and ferries are not counted)', sources['transport']))
    else:
        out.append(('Rail access', withheld('transport'), sources['transport']))
    out.append(('Road noise', f"{rec['roadNoiseUsSharePct']:g}% of residents in the 45 dB LAeq band or louder, scored "
                f"{scale('roadNoiseUsSharePct', '%')}", sources['roadNoiseUsSharePct']))
    if rec['floodSfhaPct'] is not None:
        out.append(('Flood risk', f"{rec['floodSfhaPct']:g}% of residents in the 1% annual-chance flood zone, scored "
                    f"{scale('floodSfhaPct', '%')}", sources['floodSfhaPct']))
    else:
        out.append(('Flood risk', withheld('floodSfhaPct'), sources['floodSfhaPct']))
    for label, figure, source in out:
        if not figure or not source:
            raise SystemExit(f'{name}: {label} has no figure or no source')
    return out


def render(anchors, rows):
    lines = [START, f'US_CALIFORNIA_ANCHORS = {anchors!r}', 'BAYAREA_BOROUGHS = {']
    for name, rec in rows:
        lines.append(f'    {name!r}: {rec!r},')
    lines += ['}', END]
    return '\n'.join(lines)


def lambda_constants(text):
    """{name: value} for LAMBDA_CONSTANTS, read from app.py's source as literals (each assigned once)."""
    found = {}
    for node in ast.parse(text).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in LAMBDA_CONSTANTS:
                if name in found:
                    raise SystemExit(f'{LAMBDA.name}: {name} is assigned twice; the site cannot tell which it reads')
                found[name] = ast.literal_eval(node.value)
    missing = [n for n in LAMBDA_CONSTANTS if n not in found]
    if missing:
        raise SystemExit(f'{LAMBDA.name}: {", ".join(missing)} not found as a literal; the site block reads it')
    return found


def render_site(anchors, rows, constants):
    """The site's holder: the same records as JSON, the API's anchors, top code and note, each input's source and
    year, and the US-scales sentence."""
    dump = lambda v: json.dumps(v, ensure_ascii=False)  # noqa: E731
    lines = [
        SITE_START,
        f'      const US_CALIFORNIA_ANCHORS = {dump(anchors)};',
        f"      const US_PRICE_TOP_CODE = {dump(constants['US_PRICE_TOP_CODE'])};",
        f"      const BAYAREA_CRIME_FEW_RESIDENTS_NOTE = {dump(constants['_CRIME_FEW_RESIDENTS_NOTE'])};",
        f'      const BAYAREA_INPUT_SOURCES = {dump(input_sources())};',
        f'      const BAYAREA_US_SCALES = {dump(us_scales(len(rows)))};',
        '      const BAYAREA_RECORDS = {',
    ]
    for name, rec in rows:
        lines.append(f'        {dump(name)}: {dump(rec)},')
    lines += ['      };', SITE_END]
    return '\n'.join(lines)


def span(text, start=START, end=END, where=None):
    i, j = text.find(start), text.find(end)
    if i < 0 or j < i or text.count(start) != 1 or text.count(end) != 1:
        name = start.strip().split(':')[0].lstrip('#/ ')
        raise SystemExit(f'{(where or LAMBDA).name}: the {name} markers are missing or repeated')
    return i, j + len(end)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    a = ap.parse_args()
    anchors, rows = records()
    want = render(anchors, rows)
    text = LAMBDA.read_text(encoding='utf-8')
    i, j = span(text)
    site_want = render_site(anchors, rows, lambda_constants(text))
    site = SITE.read_text(encoding='utf-8')
    si, sj = span(site, SITE_START, SITE_END, SITE)
    if a.write:
        LAMBDA.write_text(text[:i] + want + text[j:], encoding='utf-8', newline='\n')
        SITE.write_text(site[:si] + site_want + site[sj:], encoding='utf-8', newline='\n')
        held = {}
        for name, rec in rows:
            for field in rec.get('withheld', {}):
                held.setdefault(field, []).append(name)
        print(f"wrote the BAYAREA-BOROUGHS block and the site's BAYAREA-RECORDS: {len(rows)} cities, anchors {anchors}")
        for field, names in held.items():
            print(f'  {field} withheld ({len(names)}): ' + ', '.join(names))
        return 0
    stale = []
    if text[i:j].replace('\r\n', '\n') != want:
        stale.append(f'{LAMBDA.name}: the BAYAREA-BOROUGHS block')
    if site[si:sj].replace('\r\n', '\n') != site_want:
        stale.append(f'{SITE.name}: the BAYAREA-RECORDS block (the site would score other figures than the API)')
    if stale:
        print('RESULT: FAIL')
        for what in stale:
            print(f"  {what} is not what the readers' files give (re-run --write)")
        return 1
    print(f'RESULT: PASS ({len(rows)} cities in both holders, anchors {anchors})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
